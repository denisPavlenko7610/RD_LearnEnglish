def extend_vocabulary(unit):
    prompt = 'Введите английское слово или выражение по смыслу.'
    for level, kind, key, title, goal, entries in LESSONS + FOUNDATION_LESSONS:
        rule = 'Прочитайте всю фразу и обратите внимание на перевод пропуска. Введите только то, чего не хватает.\n\nI need ___ water. (Мне нужно немного воды.) → some\nI’ve just ___ home. (Я только что вернулся. Используйте get.) → got'
        cards = [(prompt, context, term, [], f'Начало ответа: {term[:max(2, len(term) // 2)].rstrip()}…', explanation)
                 for term, _, context, _, explanation in entries]
        topic = unit(f'{level.lower()}.{key}', level, title, goal, rule, cards)
        topic['track'] = 'phrasal' if kind == 'phrasal' else 'words'
        for card, (term, meaning, _, review, explanation) in zip(topic['exercises'], entries):
            slug = re.sub(r'[^a-z0-9]+', '-', term.lower()).strip('-')
            card['id'] = f'{topic["id"]}.{slug}'
            card['vocabularyTerm'] = term
            card['vocabularyMeaning'] = meaning
            card['vocabularyKind'] = kind
            card['reviewContext'] = dict(context=review, hint=card['hint'], explanation=explanation)
